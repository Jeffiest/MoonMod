#!/usr/bin/env python3
"""Build the MoonMod Pack (mods/moonmod.pack) from the first-party mods it merges.

The pack is one mod: one folder, one Mod Manager switch, one Lua script. Each merged mod is a *part* of it: the
engine runs every part inside the pack's one Lua state but as its own owner, so a part keeps its id, version,
settings, saved data (moonmod/data/<part id>/), co-op entry and everything it registers, exactly as when it was a
mod of its own. See docs/modding/PACKS.md.

The parts' sources stay in mods/<id>/ (their tests run there); this script merges them. Edit a part's own folder,
then build again:

    python tools/pack/build_pack.py            # write mods/moonmod.pack
    python tools/pack/build_pack.py --check    # fail if mods/moonmod.pack is out of date
"""
from __future__ import annotations

import argparse
import filecmp
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODS = ROOT / "mods"
PACK_ID = "moonmod.pack"
PACK_VERSION = "1.0.0"
PACK_DIR = MODS / PACK_ID

# Load order inside the script: what a part builds on comes before it; the Hub, which links to the others, comes last.
PARTS = [
    "moonmod.autosave",
    "moonmod.controls",
    "moonmod.expanded-town",
    "moonmod.modern-cloud",
    "moonmod.sirfancybacon",
    "moonmod.living-towns",
    "moonmod.dungeon-plus",
    "moonmod.rpg",
    "moonmod.roguelike",
    "moonmod.opar",
    "moonmod.vigil",
    "moonmod.hub",
]

PART_KEYS = ("id", "name", "version", "description", "coop", "settings", "dependencies", "optional_dependencies")
SKIP_FILES = {"main.lua", "mod.json"}


def read_manifest(mod_id: str) -> dict:
    return json.loads((MODS / mod_id / "mod.json").read_text(encoding="utf-8"))


def ordered_parts() -> list[str]:
    """PARTS, with anything a part names in dependencies/optional_dependencies/load_after moved ahead of it."""
    manifests = {mod_id: read_manifest(mod_id) for mod_id in PARTS}
    done: list[str] = []

    def visit(mod_id: str, trail: tuple[str, ...]) -> None:
        if mod_id in done:
            return
        if mod_id in trail:
            sys.exit(f"build_pack: load-order cycle through {mod_id}")
        manifest = manifests[mod_id]
        for key in ("dependencies", "optional_dependencies", "load_after"):
            for other in manifest.get(key, []):
                if other in manifests:
                    visit(other, trail + (mod_id,))
        done.append(mod_id)

    for mod_id in PARTS:
        visit(mod_id, ())
    return done


def part_entry(manifest: dict) -> dict:
    entry = {key: manifest[key] for key in PART_KEYS if key in manifest}
    # A part depends on another part only inside the pack; outside ones stay as the part said.
    return entry


def build_manifest(order: list[str]) -> dict:
    manifests = [read_manifest(mod_id) for mod_id in order]
    permissions: list[str] = []
    for manifest in manifests:
        for permission in manifest.get("permissions", []):
            if permission not in permissions:
                permissions.append(permission)
    games = sorted({game for manifest in manifests for game in manifest.get("games", [])})
    names = ", ".join(manifest["name"] for manifest in manifests)
    return {
        "schema_version": 1,
        "id": PACK_ID,
        "name": "MoonMod Pack",
        "version": PACK_VERSION,
        "author": "Jeffiest and the MoonMod contributors",
        "description": (
            "The MoonMod mods in one: " + names + ". One switch turns them all on or off; each part has its own "
            "switch and settings under the pack in the Mod Manager, and keeps its own saved progress."
        ),
        "framework_api": max(manifest.get("framework_api", 1) for manifest in manifests),
        "games": games,
        "entry": "main.lua",
        # Online co-op matches the parts (each listed with its own id, version and role), not the pack.
        "coop": "local",
        "permissions": permissions,
        "parts": [part_entry(manifest) for manifest in manifests],
    }


HEADER = """\
-- MoonMod Pack: the MoonMod mods in one script.
-- GENERATED by tools/pack/build_pack.py from mods/<part>/main.lua. Do not edit here: edit the part's own folder,
-- then build again.
--
-- Each part's script is handed to moonmod.part.run as source: the engine compiles it as a chunk of its own (named
-- after its file, so errors give the part's own line numbers) and runs it as its own owner (its id, settings, saved
-- data and what it registers), only when the part is switched on. Each part's globals stay its own (part_env).
local PACK_ENV = _ENV

local function part_env(id)
  local base = moonmod
  local own = setmetatable({game = setmetatable({mod_id = id}, {__index = base.game})}, {__index = base})
  return setmetatable({moonmod = own}, {__index = PACK_ENV})
end
"""


def build_script(order: list[str]) -> str:
    chunks = [HEADER]
    for mod_id in order:
        source = (MODS / mod_id / "main.lua").read_text(encoding="utf-8")
        if source.startswith("#"):
            source = "--" + source  # a shebang line is only allowed at the top of a chunk
        if "-- moonmod:end" in source or "-- moonmod:part " in source:
            sys.exit(f"build_pack: {mod_id}/main.lua contains a pack marker line")
        if not source.endswith("\n"):
            source += "\n"
        # A long string as deep as needed to hold the source unchanged. Lua drops its first newline, so the part's
        # line 1 is its file's line 1.
        level = 0
        while f"]{'=' * level}]" in source:
            level += 1
        equals = "=" * level
        chunks.append(
            f"\n-- moonmod:part {mod_id}\n"
            f'moonmod.part.run("{mod_id}", [{equals}[\n'
            f"{source}"
            f']{equals}], part_env("{mod_id}"), "{mod_id}/main.lua")\n'
            "-- moonmod:end\n"
        )
    return "".join(chunks)


def collect_files(order: list[str]) -> dict[str, Path]:
    """Every file the parts ship besides their script and manifest, at the same path inside the pack."""
    files: dict[str, Path] = {}
    for mod_id in order:
        folder = MODS / mod_id
        for path in sorted(folder.rglob("*")):
            if not path.is_file():
                continue
            relative = path.relative_to(folder).as_posix()
            if relative in SKIP_FILES:
                continue
            if relative.lower().endswith(".md"):
                relative = f"docs/{mod_id}/{relative}"  # each part's README and notes, side by side
            if relative in files:
                if not filecmp.cmp(files[relative], path, shallow=False):
                    sys.exit(f"build_pack: {relative} differs between {files[relative].parent} and {folder}")
                continue
            files[relative] = path
    return files


def readme(order: list[str]) -> str:
    lines = [
        "# MoonMod Pack",
        "",
        "The MoonMod mods in one mod. Turn the pack on in the Mod Manager and every part comes on with it; each part",
        "is listed under the pack with its own switch and settings, and keeps its own saved progress (the same as when",
        "it was a mod of its own, so nothing has to move).",
        "",
        "Generated by `tools/pack/build_pack.py` from the parts' own folders in `mods/`. Each part's own notes are in",
        "`docs/<part id>/`.",
        "",
        "| Part | Version | What it does |",
        "|---|---|---|",
    ]
    for mod_id in order:
        manifest = read_manifest(mod_id)
        about = manifest.get("description", "").split(". ")[0].rstrip(".") + "."
        lines.append(f"| {manifest['name']} (`{mod_id}`) | {manifest['version']} | {about} |")
    lines += [
        "",
        "Needs a MoonFactory engine that knows merged packs (`parts` in mod.json); older engines list the pack as",
        "invalid and leave it off.",
        "",
    ]
    return "\n".join(lines)


def render(order: list[str]) -> dict[str, bytes | Path]:
    out: dict[str, bytes | Path] = {
        "mod.json": (json.dumps(build_manifest(order), indent=2, ensure_ascii=False) + "\n").encode("utf-8"),
        "main.lua": build_script(order).encode("utf-8"),
        "README.md": readme(order).encode("utf-8"),
    }
    for relative, path in collect_files(order).items():
        out[relative] = path
    return out


def same(target: Path, content: bytes | Path) -> bool:
    if not target.is_file():
        return False
    if isinstance(content, Path):
        return filecmp.cmp(target, content, shallow=False)
    return target.read_bytes() == content


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if mods/moonmod.pack is out of date")
    parser.add_argument("--out", type=Path, default=PACK_DIR, help="where to write the pack (default mods/moonmod.pack)")
    args = parser.parse_args()

    order = ordered_parts()
    wanted = render(order)
    existing = {p.relative_to(args.out).as_posix() for p in args.out.rglob("*") if p.is_file()} if args.out.is_dir() else set()

    stale = sorted(rel for rel, content in wanted.items() if not same(args.out / rel, content))
    extra = sorted(existing - set(wanted))
    if args.check:
        if stale or extra:
            for rel in stale:
                print(f"out of date: {rel}")
            for rel in extra:
                print(f"not from any part: {rel}")
            print("mods/moonmod.pack is out of date: run python tools/pack/build_pack.py")
            return 1
        print(f"mods/moonmod.pack is up to date ({len(order)} parts, {len(wanted)} files)")
        return 0

    for rel in extra:
        (args.out / rel).unlink()
    for rel in stale:
        target = args.out / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        content = wanted[rel]
        if isinstance(content, Path):
            shutil.copyfile(content, target)
        else:
            target.write_bytes(content)
    for folder in sorted((p for p in args.out.rglob("*") if p.is_dir()), key=lambda p: len(p.parts), reverse=True):
        if not any(folder.iterdir()):
            folder.rmdir()
    size = (args.out / "main.lua").stat().st_size
    print(f"built {args.out.relative_to(ROOT) if args.out.is_relative_to(ROOT) else args.out}: "
          f"{len(order)} parts, {len(wanted)} files ({len(stale)} written, {len(extra)} removed), script {size // 1024} KiB")
    print("order: " + ", ".join(order))
    return 0


if __name__ == "__main__":
    sys.exit(main())
