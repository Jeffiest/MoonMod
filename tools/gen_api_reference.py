#!/usr/bin/env python3
"""Write docs/api/OPERATIONS.md: every catalogued operation and event, read from the port patches.

The operation and event catalogs live in each port's `port/src/moonmod/api.cpp`, which this repository carries inside
`ports/<game>/moonfactory-<game>.patch`. A port marks the operations it has bound to the game in its
`Configure...Api(RuntimeConfig &)` functions; the runtime's own (core) operations are listed in `IsCoreApiOperation`.
This script reads all three and writes one table per domain.

    python tools/gen_api_reference.py            # rewrite docs/api/OPERATIONS.md
    python tools/gen_api_reference.py --check    # exit 1 when the file is out of date (for CI)

Run it after a patch changes the catalog. The running game stays the authority: `moonmod.api.list()` reports what
that build supports, with a reason for each operation it does not.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "api" / "OPERATIONS.md"
PORTS = (
    ("chronicle", "Chronicle", ROOT / "ports" / "chronicle" / "moonfactory-chronicle.patch"),
    ("chronicle-two", "Chronicle Two", ROOT / "ports" / "chronicle-two" / "moonfactory-chronicle-two.patch"),
)

# Where each domain is written up. A domain missing here links to the overview.
CHAPTERS = {
    "runtime.md": ("info", "compat", "api", "events", "save", "content", "localization", "commands", "scripts",
                   "quests", "skills", "debug", "mods"),
    "assets.md": ("resources", "audio", "text", "models", "animations"),
    "ui.md": ("ui", "input", "render"),
    "player.md": ("player", "party", "characters", "economy"),
    "items-weapons.md": ("items", "weapons", "shops", "inventions"),
    "combat.md": ("combat", "entities", "physics", "monsters", "effects"),
    "dungeons.md": ("dungeons",),
    "georama.md": ("georama",),
    "world.md": ("world", "locations", "title", "session", "photos"),
    "online.md": ("net", "messages"),
}
DOMAIN_CHAPTER = {domain: chapter for chapter, domains in CHAPTERS.items() for domain in domains}

OPERATION = re.compile(
    r'^\+    \{"([a-z_0-9]+\.[a-z_0-9]+)", "([a-z_0-9]+)", "([a-z_0-9]+)", "([a-z_]*)", "([a-z._]*)",'
    r'\s*\n?\+?\s*"((?:[^"\\]|\\.)*)"', re.MULTILINE)
EVENT = re.compile(r'^\+    \{"([a-z_0-9.]+)", "([a-z_0-9]+)", "([a-z-]+)",\s*\n?\+?\s*"((?:[^"\\]|\\.)*)"', re.MULTILINE)


def unescape(text: str) -> str:
    return text.replace('\\"', '"').replace("\\\\", "\\")


def read_port(patch: Path) -> dict:
    text = patch.read_text(encoding="utf-8", errors="replace")
    api = re.search(r"^\+\+\+ b/port/src/moonmod/api\.cpp\n(.*?)(?=^diff --git )", text, re.S | re.M)
    if not api:
        raise SystemExit(f"{patch}: no port/src/moonmod/api.cpp in the patch")
    source = api.group(1)
    split = source.index("kEventCatalog")
    operations = {m[0]: {"domain": m[1], "phase": m[3], "permission": m[4], "summary": unescape(m[5])}
                  for m in OPERATION.findall(source[:split])}
    events = {m[0]: {"domain": m[1], "games": m[2], "summary": unescape(m[3])} for m in EVENT.findall(source[split:])}
    core = set(re.findall(r'path == "([a-z_0-9.]+)"', source))

    supported = core & operations.keys()
    for start in re.finditer(r"^\+void Configure\w*Api\(RuntimeConfig[^)]*\)\s*\{", text, re.M):
        body = text[start.start():text.index("\n+}\n", start.start())]
        refused = set(re.findall(r'\{"([a-z_0-9.]+)", false', body))
        named = set(re.findall(r'"([a-z_0-9]+\.[a-z_0-9]+)"', body)) & operations.keys()
        supported |= named - refused
    return {"operations": operations, "events": events, "supported": supported}


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def render() -> str:
    ports = {key: read_port(patch) for key, _, patch in PORTS}
    first, second = ports["chronicle"], ports["chronicle-two"]
    paths = list(first["operations"])
    paths += [path for path in second["operations"] if path not in first["operations"]]
    domains: dict[str, list[str]] = {}
    for path in paths:
        spec = first["operations"].get(path) or second["operations"][path]
        domains.setdefault(spec["domain"], []).append(path)

    both = sum(1 for p in paths if p in first["supported"] and p in second["supported"])
    lines = [
        "# Operation and event index",
        "",
        "<!-- Generated by tools/gen_api_reference.py from the port patches. Do not edit by hand. -->",
        "",
        "Every operation in the `game.*` catalog and every event either port lists, read from the catalogs in the",
        "port patches. The chapters linked from each heading say how to use them; start at the [API overview](../API.md).",
        "",
        f"- **{len(paths)} operations** in {len(domains)} domains: {len(first['supported'])} supported on Chronicle,",
        f"  {len(second['supported'])} on Chronicle Two, {both} on both.",
        "- Call one as `game.<domain>.<operation>(arguments)` or `moonmod.api.call(\"<domain>.<operation>\", arguments)`.",
        "- **Permission** is what the mod's `mod.json` must list under `permissions`. A dash means none.",
        "- **Phase** is where the call is safe: `any`, `simulation` (during play), `content` (registration) or `ui`.",
        "- **C1** and **C2** say whether Chronicle (Dark Cloud) and Chronicle Two (Dark Chronicle) bind the operation.",
        "  An operation a port does not bind fails with `code = \"unsupported\"` and a reason.",
        "",
        "The running game is the authority: `moonmod.api.list()` and `moonmod.api.supports(path)` report what that",
        "build supports. A few operations also depend on the build (`net.*` needs a network library).",
        "",
        "## Domains",
        "",
        "| Domain | Operations | C1 | C2 | Chapter |",
        "| --- | ---: | ---: | ---: | --- |",
    ]
    for domain, names in sorted(domains.items()):
        chapter = DOMAIN_CHAPTER.get(domain)
        link = f"[{chapter}]({chapter})" if chapter else "[overview](../API.md)"
        lines.append(f"| [`game.{domain}`](#game{domain.replace('_', '')}) | {len(names)} | "
                     f"{sum(1 for n in names if n in first['supported'])} | "
                     f"{sum(1 for n in names if n in second['supported'])} | {link} |")
    lines += ["", "## Operations"]
    for domain, names in sorted(domains.items()):
        chapter = DOMAIN_CHAPTER.get(domain)
        lines += ["", f"### `game.{domain}`", ""]
        if chapter:
            lines += [f"Written up in [{chapter}]({chapter}).", ""]
        lines += ["| Operation | Permission | Phase | C1 | C2 | What it does |", "| --- | --- | --- | :-: | :-: | --- |"]
        for path in names:
            spec = first["operations"].get(path) or second["operations"][path]
            marks = ["yes" if path in port["supported"] else "–" for port in (first, second)]
            lines.append(f"| `{path}` | {'`' + spec['permission'] + '`' if spec['permission'] else '–'} | "
                         f"{spec['phase']} | {marks[0]} | {marks[1]} | {cell(spec['summary'])} |")

    events = dict(first["events"])
    for name, spec in second["events"].items():
        events.setdefault(name, spec)
    lines += [
        "", "## Events", "",
        "The events `game.events.list()` reports. Subscribe with `moonmod.on(name, callback)` or",
        "`game.events.subscribe(name, callback)`. Some operations also send events of their own to the mod that asked",
        "(a panel's answer, a floor's gate); those are described with the operation in its chapter.",
        "",
        "| Event | Domain | C1 | C2 | When |", "| --- | --- | :-: | :-: | --- |",
    ]
    for name, spec in events.items():
        marks = ["yes" if name in port["events"] else "–" for port in (first, second)]
        lines.append(f"| `{name}` | {spec['domain']} | {marks[0]} | {marks[1]} | {cell(spec['summary'])} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when docs/api/OPERATIONS.md is out of date")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date: run python tools/gen_api_reference.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
