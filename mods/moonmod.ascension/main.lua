local function skill_budget(character)
  character=saved_number(character,active_skill_character or active_character_index(),0,5)
  local level=get_char_progression(character)
  local level_for_points=math.min(level,max_level())
  local earned=(level_for_points-1)*setting("skill_points_per_level",1,0,5)+
    math.floor((level_for_points-1)/5)*setting("skill_bonus_points_every_5",1,0,5)
  local spent=0
  local listed=game.skills.list()
  for _, skill in ipairs((listed and listed.skills) or {}) do
    local id=skill.id or ""
    if id:sub(1,18)=="moonmod.ascension:" then
      local local_id=id:sub(19)
      spent=spent+character_skill_rank(character,local_id)*(skill_costs[local_id] or 1)
    end
  end
  return earned - spent
end

