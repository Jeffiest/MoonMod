    gilda_per_tier_percent=saved_number(result.gilda_per_tier_percent,40,0,300),
    xp_per_tier_percent=saved_number(result.xp_per_tier_percent,25,0,200),
    champion_chance_per_tier=saved_number(result.champion_chance_per_tier,4,0,20)}
end
