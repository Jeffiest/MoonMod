local function choose(list)
  if type(list)~="table" or #list==0 then return nil end
  return list[math.random(#list)]
end
local function roll_champion_loot(dungeon,floor,model)
  local data=LEGACY_LOOT.dungeons[dungeon]
  if not data then return nil end
  local rare=data.rare[model]
  local common=data.common[model]
  local item
  if rare and math.random(100)<=setting("champion_rare_drop_chance",5,0,100) then
    item=choose(rare)
  elseif common and math.random(100)<=setting("champion_common_drop_chance",30,0,100) then
    item=choose(common)
  end
  if item then return item,data.boosts[item] end
  if data.back_key and math.random(100)<=35 then return data.back_key end
  if math.random(100)<=15 then
    local pool=floor<=data.split_floor and data.weapons_early or data.weapons_late
    item=choose(pool);if item then return item end
  end
  if math.random(100)<=80 then
    item=choose(math.random(100)<=60 and LEGACY_LOOT.attachmentsTableLucky or LEGACY_LOOT.attachmentsTableUnlucky)
  else
    item=choose(math.random(100)<=60 and LEGACY_LOOT.itemTableLucky or LEGACY_LOOT.itemTableUnlucky)
  end
  return item
end
local function clamp_weapon_value(value)
  return math.max(0,math.min(32767,math.floor((tonumber(value) or 0)+0.5)))
end
local function update_picked_up_weapon(event,boost)
  local item=tonumber(event.native_item_no)
  local character=event.character
  local slot=tonumber(event.slot)
  if not item or item<257 or not character or not slot then return false end
  local ok,weapon=pcall(game.weapons.get,"chronicle:weapon:"..item)
  if not ok or type(weapon)~="table" then return false end
  local instance
  for _,owned in ipairs(weapon.instances or {}) do
    if owned.character==character and owned.slot==slot then instance=owned;break end
  end
  if not instance then return false end
  local stats=instance.stats or {}
  local request={id=weapon.id,character=character,slot=slot}
  if boost then
    if boost.attack then request.attack=clamp_weapon_value((stats.attack or 0)+boost.attack) end
    if boost.endurance then request.endurance=clamp_weapon_value((stats.endurance or 0)+boost.endurance) end
    if boost.speed then request.speed=clamp_weapon_value((stats.speed or 0)+boost.speed) end
    if boost.magic then request.magic=clamp_weapon_value((stats.magic or 0)+boost.magic) end
    if boost.durability then request.durability=clamp_weapon_value((stats.durability or 0)+boost.durability) end
    if boost.elem then
      request.elem={};for i=1,5 do request.elem[i]=math.min(127,(instance.elements[i] or 0)+(boost.elem[i] or 0)) end
    end
    if boost.vs then
      request.vs_monster={};for i=1,10 do request.vs_monster[i]=math.min(127,(instance.vs_monster[i] or 0)+(boost.vs[i-1] or 0)) end
    end
    if boost.s1 or boost.s2 then request.flags=(instance.flags or 0)|(boost.s1 or 0)|((boost.s2 or 0)<<8) end
  else
    if moonmod.settings.get("weapon_loot_rolls")==false then return false end
    local roll=math.random(100);local rarity
    if roll<=1 then rarity={name="Legendary",lo=.35,hi=.45}
    elseif roll<=5 then rarity={name="Exquisite",lo=.20,hi=.30}
    elseif roll<=15 then rarity={name="Superior",lo=.10,hi=.20}
    elseif roll<=40 then rarity={name="Fine",lo=.05,hi=.10} end
    if not rarity then return false end
    local factor=1+rarity.lo+math.random()*(rarity.hi-rarity.lo)
    for _,key in ipairs({"attack","endurance","speed","magic","durability"}) do
      request[key]=clamp_weapon_value((stats[key] or 0)*factor)
    end
    game.ui.notify({message=rarity.name.." weapon! Improved stats"})
  end
  local changed,err=game.weapons.stats_set(request)
  if not changed then moonmod.log("warn","Weapon reward update failed: "..(type(err)=="table" and err.message or tostring(err))) end
  return changed~=nil
end
