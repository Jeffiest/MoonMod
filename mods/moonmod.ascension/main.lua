local function add_xp(char_idx, amount)
  if active_native_slot_id == nil or amount <= 0 or char_idx < 0 or char_idx > 5 then return end
  amount=math.max(1,math.floor(amount*(1+0.05*character_skill_rank(char_idx,"focus.scholar"))+0.5))
  local level, xp, paragon = get_char_progression(char_idx)
  local leveled = false
  local paragon_up = false

  xp = xp + amount

  while level < max_level() and xp >= xp_needed_for_level(level) do
    xp = xp - xp_needed_for_level(level)
    level = level + 1
    leveled = true
    local player = game.characters.get({id=CHARACTERS[char_idx]})
    if player then
      local hp_gain=setting("hp_per_level",3,0,25)
      game.player.set({character = CHARACTERS[char_idx], max_hp = math.min(999, player.max_hp + hp_gain)})
    end
    if player and player.hp > 0 then game.player.heal({ character = CHARACTERS[char_idx], amount = setting("hp_per_level",3,0,25) * 10 }) end
  end

  if level >= max_level() then
    while paragon < 50 and xp >= paragon_needed_for_rank(paragon) do
      xp = xp - paragon_needed_for_rank(paragon)
      paragon = paragon + 1
      paragon_up = true
      local player = game.characters.get({id=CHARACTERS[char_idx]})
      if player then
        local hp_gain=setting("paragon_hp_per_rank",4,0,25)
        game.player.set({character = CHARACTERS[char_idx], max_hp = math.min(999, player.max_hp + hp_gain)})
      end
      if player and player.hp > 0 then game.player.heal({ character = CHARACTERS[char_idx], amount = setting("paragon_hp_per_rank",4,0,25) * 10 }) end
    end
    if paragon >= 50 then xp = 0 end
  end

  set_char_progression(char_idx, level, xp, paragon)
  update_combat_damage()

  local char_name = CHARACTERS[char_idx]:upper()
  if leveled then
    game.ui.notify({ message = "LEVEL UP! " .. char_name .. " is now Level " .. level .. "!" })
    moonmod.log("info", "Ascension: " .. char_name .. " leveled up to " .. level)
  end
  if paragon_up then
    game.ui.notify({ message = "PARAGON RANK! " .. char_name .. " reached Paragon " .. paragon .. "!" })
    moonmod.log("info", "Ascension: " .. char_name .. " reached Paragon rank " .. paragon)
  end
end

