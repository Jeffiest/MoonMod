-- Award XP on enemy defeat
moonmod.on("game.enemy_defeated", function(event)
  -- Weapon mastery is character independent in the legacy mod: any party
  -- character's weapon earns progress. Record it before Ascension's separate
  -- XP attribution checks, so an unknown/scripted killer can still count when
  -- the native death event captured a weapon.
  mastery_record(event)
  -- Native death events capture the killer's character slot before the monster is recycled.
  local char_idx=event.attacker
  if type(char_idx)~="number" or char_idx<0 or char_idx>5 then
    local player=game.player.get()
    char_idx=player and player.character_id or nil
  end
  if type(char_idx)~="number" or char_idx<0 or char_idx>5 then return end
  -- Legacy XP uses 45% of the enemy's max HP plus its native EXP stat.
  -- Older producers may omit max HP, so retain their listed reward fallback.
  local enemy_record=event.entity and ascension_enemy_records[event.entity] or nil
  local enemy_hp=enemy_record and enemy_record.base_hp or (type(event.enemy_max_hp)=="number" and event.enemy_max_hp or 0)
  local enemy_exp=enemy_record and enemy_record.base_exp or (type(event.reward_exp)=="number" and event.reward_exp or 0)
  local reward_multiplier=enemy_record and enemy_record.champion and enemy_record.xp_multiplier or 1
  local tier_info=dungeon_plus_info()
  local tier_xp_multiplier=1+(tier_info.xp_per_tier_percent/100)*tier_info.tier
  local reward=enemy_hp>0 and (enemy_hp*setting("xp_per_max_hp_percent",45,0,200)/100+enemy_exp)*reward_multiplier*tier_xp_multiplier or
    (enemy_exp>0 and enemy_exp or 20)*reward_multiplier*tier_xp_multiplier
  add_xp(char_idx,math.max(1,math.floor(reward+0.5)))
  if enemy_record and enemy_record.loot_item and enemy_record.loot_item>=257 and enemy_record.loot_boost then
    local item=enemy_record.loot_item;local queue=champion_boosts[item] or {}
    queue[#queue+1]={boost=enemy_record.loot_boost,visit=loot_visit_key(game.world.get())}
    champion_boosts[item]=queue
  end
  if event.entity then ascension_enemy_records[event.entity]=nil end
  local ranks=skill_ranks()
  local hunter=character_skill_rank(char_idx,"focus.treasure_hunter")
  local money=type(event.reward_money)=="number" and event.reward_money or 0
  -- Legacy regular enemies grant the configured extra Gilda share; champions
  -- instead use the champion multiplier already written to their native reward.
  -- Treasure Hunter scales the appropriate base (regular bonus or champion reward).
  local gilda_bonus=enemy_record and enemy_record.champion and (0.10*hunter) or
    (setting("gilda_bonus_percent",50,0,500)/100*(1+0.10*hunter))
  local extra=math.min(32767,math.floor(money*gilda_bonus+0.5))
  if extra>0 then game.economy.add({amount=extra}) end
end)

