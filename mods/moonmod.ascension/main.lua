local function mastery_summary(weapon_id, kills)
  local rank = mastery_rank(kills)
  local next_kill = MASTERY_THRESHOLDS[rank + 1]
  local bonus = math.floor(rank * (moonmod.settings.get("mastery_damage_per_rank") or 2) + 0.5)
  local progress = next_kill and string.format("%d/%d kills; %d to next rank", kills, next_kill, next_kill-kills)
                              or string.format("%d kills; maximum rank", kills)
  return string.format("%s  |  Mastery %d/5  |  %s  |  +%d%% damage", mastery_weapon_name(weapon_id), rank, progress, bonus)
end

