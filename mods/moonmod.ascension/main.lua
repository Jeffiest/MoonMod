local function active_character_index()
  local ok, player = pcall(game.player.get)
  local index = ok and type(player) == "table" and player.character_id or nil
  return saved_number(index, 0, 0, 5)
end

local function native_slot_identity()
  local ok, result = pcall(game.save.slot_id)
  local value = ok and type(result) == "table" and result.slot_id or nil
  local generation = ok and type(result) == "table" and result.slot_generation or nil
  if type(value) ~= "number" or value < 1 or value ~= math.floor(value) then return nil end
  if type(generation) ~= "number" or generation < 1 or generation ~= math.floor(generation) then return value, nil end
  return value, tostring(value) .. ":" .. tostring(generation)
end

local function all_slot_data()
  local data = moonmod.storage.get(ASCENSION_SLOTS_KEY)
  return type(data) == "table" and data or {}
end

local function persist_slot_data(data)
  checked(moonmod.storage.set(ASCENSION_SLOTS_KEY, data))
end

local function slot_record(slot_id, create)
  if type(slot_id) ~= "string" then return nil end
  local data = all_slot_data()
  local record = data[slot_id]
  if type(record) ~= "table" then
    if not create then return nil end
    record = {}
    data[slot_id] = record
    persist_slot_data(data)
  end
  return record
end

local function snapshot_registered_skills()
  local snapshot = {}
  local ok, listed = pcall(game.skills.list)
  if not ok or type(listed) ~= "table" then return snapshot end
  for _, skill in ipairs(listed.skills or {}) do
    if type(skill.id) == "string" and skill.id:sub(1, 18) == "moonmod.ascension:" then
      snapshot[skill.id] = saved_number(skill.rank, 0, 0, 99)
    end
  end
  return snapshot
end

local function migrate_legacy_slot_data(slot_id, slot_key)
  local data = all_slot_data()
  local key = slot_key
  local record = type(data[key]) == "table" and data[key] or {}
  local legacy_key = tostring(slot_id)
  local moved_legacy_slot = false
  if data[key] == nil and type(data[legacy_key]) == "table" then
    record = data[legacy_key]
    data[legacy_key] = nil
    moved_legacy_slot = true
  end
  local migrations = moonmod.storage.get(SLOT_MIGRATIONS_KEY)
  if type(migrations) ~= "table" then migrations = {} end
  local dirty = false
  if not migrations.progression then
    if type(record.progression) ~= "table" then
      local old = moonmod.storage.get("progression_v2")
      if type(old) ~= "table" then old = {} end
      local copied = {}
      for character = 0, 5 do
        local old_entry = old[tostring(character)] or {}
        local level = old_entry.level or moonmod.storage.get(get_char_key(character, "level"))
        local xp = old_entry.xp or moonmod.storage.get(get_char_key(character, "xp"))
        local paragon = old_entry.paragon or moonmod.storage.get(get_char_key(character, "paragon"))
        if level ~= nil or xp ~= nil or paragon ~= nil then
          copied[tostring(character)] = {
            level = saved_number(level, 1, 1, 100),
            xp = saved_number(xp, 0, 0, 1000000),
            paragon = saved_number(paragon, 0, 0, 50)
          }
        end
      end
      record.progression = copied
      dirty = true
    end
    migrations.progression = true
  end
  if not migrations.mastery then
    if type(record.weapon_mastery) ~= "table" then
      local old = moonmod.storage.get("weapon_mastery_v1")
      record.weapon_mastery = type(old) == "table" and old or {}
      dirty = true
    end
    migrations.mastery = true
  end
  if type(record.skill_profiles) ~= "table" then record.skill_profiles = {} end
  -- Upgrade the previous shared rank set into the character who was active
  -- when its save was first migrated. New saves start with six empty trees.
  if not migrations.skills then
    if next(record.skill_profiles) == nil then
      if type(record.skills) == "table" then
        record.skill_profiles[tostring(active_character_index())] = record.skills
      else
        record.skill_profiles[tostring(active_character_index())] = snapshot_registered_skills()
      end
    end
    record.skills = nil
    migrations.skills = true
    dirty = true
  elseif type(record.skills) == "table" then
    record.skill_profiles[tostring(active_character_index())] = record.skills
    record.skills = nil
    dirty = true
  end
  data[key] = record
  if dirty or moved_legacy_slot then persist_slot_data(data) end
  checked(moonmod.storage.set(SLOT_MIGRATIONS_KEY, migrations))
end

local function save_slot_skills(slot_id, character)
  if type(slot_id) ~= "string" then return end
  local data = all_slot_data()
  local record = type(data[slot_id]) == "table" and data[slot_id] or {}
  if type(record.skill_profiles) ~= "table" then record.skill_profiles = {} end
  local index = saved_number(character, active_skill_character or 0, 0, 5)
  record.skill_profiles[tostring(index)] = snapshot_registered_skills()
  data[slot_id] = record
  persist_slot_data(data)
end

local function store_slot_skill_rank(slot_id, character, skill_id, rank)
  if type(slot_id) ~= "string" or type(skill_id) ~= "string" or skill_id:sub(1, 18) ~= "moonmod.ascension:" then return end
  local data = all_slot_data()
  local record = type(data[slot_id]) == "table" and data[slot_id] or {}
  if type(record.skill_profiles) ~= "table" then record.skill_profiles = {} end
  local character_key = tostring(saved_number(character, active_skill_character or 0, 0, 5))
  if type(record.skill_profiles[character_key]) ~= "table" then record.skill_profiles[character_key] = {} end
  record.skill_profiles[character_key][skill_id] = saved_number(rank, 0, 0, 99)
  data[slot_id] = record
  persist_slot_data(data)
end

local function apply_slot_skills(slot_id, character)
  local record = slot_record(slot_id, false) or {}
  local profiles = type(record.skill_profiles) == "table" and record.skill_profiles or {}
  local character_key = tostring(saved_number(character, 0, 0, 5))
  local desired = type(profiles[character_key]) == "table" and profiles[character_key] or {}
  local ok, listed = pcall(game.skills.list)
  if not ok or type(listed) ~= "table" then return end
  local nodes = {}
  for _, skill in ipairs(listed.skills or {}) do
    if type(skill.id) == "string" and skill.id:sub(1, 18) == "moonmod.ascension:" then
      nodes[#nodes + 1] = {id = skill.id, rank = saved_number(desired[skill.id], 0, 0, skill.max_rank or 99), current = skill.rank or 0}
    end
  end
  syncing_native_slot = true
  for _, skill in ipairs(nodes) do
    if skill.current ~= 0 then pcall(game.skills.set_rank, {id = skill.id, rank = 0}) end
  end
  local pending = {}
  for _, skill in ipairs(nodes) do if skill.rank > 0 then pending[#pending + 1] = skill end end
  for _ = 1, #nodes do
    local progressed = false
    for index = #pending, 1, -1 do
      local skill = pending[index]
      local ok, result = pcall(game.skills.set_rank, {id = skill.id, rank = skill.rank})
      if ok and result then table.remove(pending, index); progressed = true end
    end
    if not progressed then break end
  end
  syncing_native_slot = false
  if #pending > 0 then
    moonmod.log("warn", "Some saved Ascension ranks could not be restored because their prerequisites are unavailable")
  end
end

local function sync_native_save_slot()
  local slot_id, slot_key = native_slot_identity()
  if slot_id == nil or slot_key == nil or slot_key == active_native_slot_key then return false end
  if active_native_slot_key ~= nil then save_slot_skills(active_native_slot_key, active_skill_character) end
  migrate_legacy_slot_data(slot_id, slot_key)
  active_native_slot_id = slot_id
  active_native_slot_key = slot_key
  active_skill_character = active_character_index()
  apply_slot_skills(slot_key, active_skill_character)
  return true
end

local function sync_active_skill_character()
  local next_character = active_character_index()
  if next_character == active_skill_character then return false end
  if active_native_slot_key then save_slot_skills(active_native_slot_key, active_skill_character) end
  active_skill_character = next_character
  if active_native_slot_key then apply_slot_skills(active_native_slot_key, active_skill_character) end
  return true
end

local function get_char_progression(char_idx)
  local record = slot_record(active_native_slot_key, false) or {}
  local progression = type(record.progression) == "table" and record.progression or {}
  local data = progression[tostring(char_idx)] or {}
  local level, xp, paragon = data.level, data.xp, data.paragon
  return saved_number(level,1,1,100), saved_number(xp,0,0,1000000), saved_number(paragon,0,0,50)
end
local function set_char_progression(char_idx, level, xp, paragon)
  if active_native_slot_id == nil then return end
  local data = all_slot_data()
  local key = active_native_slot_key
  local record = type(data[key]) == "table" and data[key] or {}
  local progression = type(record.progression) == "table" and record.progression or {}
  progression[tostring(char_idx)] = {level=level,xp=xp,paragon=paragon}
  record.progression = progression
  data[key] = record
  persist_slot_data(data)
end

