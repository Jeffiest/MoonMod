-- Native max HP is saved in each numbered Chronicle slot. Keep the baseline
-- and amount contributed by Toughness under that slot ID so rank changes and
-- respecs only adjust the save currently loaded.
local function apply_toughness_hp()
  local slot_id, slot_key = native_slot_identity()
  if type(slot_id) ~= "number" or type(slot_key) ~= "string" then return end
  local party = game.party.list()
  if type(party) ~= "table" then return end
  local all = moonmod.storage.get("toughness_hp_by_slot_v1") or {}
  local key = slot_key
  local legacy_key = tostring(slot_id)
  if all[key] == nil and type(all[legacy_key]) == "table" then
    all[key] = all[legacy_key]
    all[legacy_key] = nil
    checked(moonmod.storage.set("toughness_hp_by_slot_v1", all))
  end
  local slot_data = all[key] or {}
  local dirty = all[key] == nil
  for _, member in ipairs(party) do
    local name = type(member.character_id) == "number" and CHARACTERS[member.character_id] or nil
    if name then
      local rank = character_skill_rank(member.character_id,"vitality.toughness")
      local character = game.characters.get({id=name})
      if character and type(character.max_hp) == "number" then
        local record = slot_data[name]
        if record == nil and rank > 0 then
          record = {base=character.max_hp, bonus=0}
          slot_data[name] = record
          dirty = true
        end
        if record then
          local base = type(record.base) == "number" and record.base or character.max_hp
          local bonus = type(record.bonus) == "number" and record.bonus or 0
          local previous_rank = type(record.rank) == "number" and record.rank or 0
          local expected = base + bonus
          local recompute = rank ~= previous_rank
          if character.max_hp < expected then
            -- A newly created save may reuse a deleted slot number. Reset its
            -- ledger when its native HP is below the previous slot's recorded
            -- value instead of interpreting the difference as level growth.
            base, bonus = character.max_hp, 0
            recompute = true
          else
            base = math.max(1, base + character.max_hp - expected)
          end
          local target = base + bonus
          if recompute then
            target = base
            for _ = 1, rank do target = target + math.max(1, math.floor(target * 0.04 + 0.5)) end
          end
          target = math.min(999, target)
          if target ~= character.max_hp then
            local set_ok, changed = pcall(game.player.set, {character=name, max_hp=target})
            if set_ok and changed then
              record.base, record.bonus, record.rank = base, target - base, rank
              dirty = true
            end
          elseif record.base ~= base or record.bonus ~= target - base or record.rank ~= rank then
            record.base, record.bonus, record.rank = base, target - base, rank
            dirty = true
          end
        end
      end
    end
  end
  if dirty then
    all[key] = slot_data
    checked(moonmod.storage.set("toughness_hp_by_slot_v1", all))
  end
end

