local function checked(value, err)
  if value == nil then error(type(err) == "table" and err.message or tostring(err)) end
  return value
end
local function saved_number(value, fallback, low, high)
  if type(value) ~= "number" or value ~= value then return fallback end
  return math.max(low, math.min(high, math.floor(value)))
end
local function setting(id, fallback, low, high)
  return saved_number(moonmod.settings.get(id),fallback,low,high)
end
local function setting_number(id, fallback, low, high)
  local value=moonmod.settings.get(id)
  if type(value)~="number" or value~=value then return fallback end
  return math.max(low,math.min(high,value))
end
