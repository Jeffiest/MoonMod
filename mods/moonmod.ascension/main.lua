local function update_defense()
  local listed = game.skills.list()
  local iron_skin = 0
  for _, skill in ipairs((listed and listed.skills) or {}) do
    if skill.id == "moonmod.ascension:vitality.iron_skin" then iron_skin=skill.rank end
  end
  local player=game.player.get()
  local level=1
  if player and type(player.character_id)=="number" then level=get_char_progression(player.character_id) end
  local mitigation_cap=setting("mitigation_cap_percent",40,0,90)/100
  local level_mitigation=math.min(mitigation_cap,
    setting("mitigation_per_level_hundredths",80,0,1000)/10000*math.max(0,level-1))
  local world=game.world.get() or {}
  local incoming=1+setting_number("damage_taken_per_floor_percent",2,0,50)/100*math.max(0,world.floor_id or 0)+
    setting("damage_taken_per_dungeon_percent",8,0,100)/100*math.max(0,world.dungeon_id or 0)
  local mitigation=math.min(mitigation_cap,level_mitigation+0.02*iron_skin)
  local multiplier=incoming*(1-mitigation)
  if champion_threat then multiplier=multiplier*setting("champion_damage_taken_percent",150,100,500)/100 end
  if berserk_active() then multiplier=multiplier*1.20 end
  checked(game.combat.register_player_formula({id="toughness",operation="multiply",value=multiplier,priority=50}))
end

local function update_enemy_scaling()
  local world=game.world.get() or {}
  if world.context~="dungeon" then champion_threat=false;return end
  local roster=game.entities.query({type="monster"})
  if not roster or type(roster.entities)~="table" then return end
  local player=game.player.get()
  local player_position=player and player.position
  local threat_radius=setting("champion_threat_range",22,0,100)
  local threat_radius_sq=threat_radius*threat_radius
  local threatened=false
  local dungeon=math.max(0,tonumber(world.dungeon_id) or 0)
  local floor=math.max(0,tonumber(world.floor_id) or 0)
  local tier_info=dungeon_plus_info()
  local tier=tier_info.tier
  local hp_scale=1+setting("enemy_hp_per_dungeon_percent",10,0,100)/100*dungeon+
    setting("enemy_hp_per_floor_half_percent",7,0,40)/200*floor
  hp_scale=hp_scale*(1+(tier_info.hp_per_tier_percent/100)*tier)
  for _,enemy in ipairs(roster.entities) do
    local handle=enemy.entity_id
    if type(handle)=="string" and enemy.revealed~=false then
      local record=ascension_enemy_records[handle]
      if not record then
        local base_hp=enemy.health and tonumber(enemy.health.maximum) or 0
        local combat=enemy.combat or {}
        local base_defense=tonumber(combat.defense) or 0
        local base_money=tonumber(combat.reward_money) or 0
        local base_exp=tonumber(combat.reward_exp) or 0
        if base_hp>0 then
          local drop_item=enemy.definition and tonumber(enemy.definition.drop_item) or -1
          local champion_chance=math.min(100,setting("champion_chance_percent",8,0,100)+tier_info.champion_chance_per_tier*tier)
          local champion=drop_item<0 and base_hp<setting("champion_max_base_hp",600,1,100000) and
            math.random(100)<=champion_chance
          local loot_item,loot_boost
          if champion then loot_item,loot_boost=roll_champion_loot(dungeon,floor,tonumber(enemy.native_model_id)) end
          local champion_hp=champion and setting("champion_hp_multiplier_percent",300,100,1000)/100 or 1
          local champion_defense=champion and setting("champion_defense_multiplier_percent",150,100,500)/100 or 1
          local reward_multiplier=champion and setting("champion_reward_multiplier_percent",300,100,1000)/100 or 1
          local xp_multiplier=champion and setting("champion_xp_multiplier_percent",300,100,1000)/100 or 1
          local scaled_hp=math.min(1000000,math.floor(base_hp*hp_scale*champion_hp+0.5))
          local defense=math.max(0,math.min(32767,math.floor((base_defense+
            setting("enemy_defense_hundredths_per_floor",15,0,100)/100*floor+tier_info.defense_per_tier*tier)*champion_defense+0.5)))
          local money=math.min(2147483647,math.floor(math.max(0,base_money)*
            (1+tier_info.gilda_per_tier_percent*tier/100)*(champion and reward_multiplier or 1)+0.5))
          local update={entity=handle,hp=scaled_hp,max_hp=scaled_hp,defense=defense,reward_money=money}
          if loot_item then update.drop_item=loot_item end
          local changed,err=game.entities.set_stats(update)
          local applied=changed~=nil
          record={base_hp=base_hp,base_exp=base_exp,base_money=base_money,champion=champion and applied,
            reward_multiplier=reward_multiplier,
            xp_multiplier=xp_multiplier,
            scaled=changed~=nil,model=enemy.native_model_id,
            loot_item=applied and loot_item or nil,loot_boost=applied and loot_boost or nil}
          ascension_enemy_records[handle]=record
          if record.champion then
            local scaled,scale_err=game.entities.scale_set({entity=handle,
              scale=setting("champion_size_percent",150,100,300)/100})
            record.size_scaled=scaled~=nil
            if not scaled then moonmod.log("warn","Champion size failed: "..(type(scale_err)=="table" and scale_err.message or tostring(scale_err))) end
          end
          if not changed then
            moonmod.log("warn","Enemy scaling failed: "..(type(err)=="table" and err.message or tostring(err)))
          elseif record.champion then
            game.ui.notify({message="CHAMPION: enemy model "..tostring(enemy.native_model_id or "?").." has emerged"})
          end
        end
      end
      record=ascension_enemy_records[handle]
      local position=enemy.position
      if record and record.champion and player_position and position then
        local dx=(position.x or 0)-(player_position.x or 0)
        local dz=(position.z or 0)-(player_position.z or 0)
        if dx*dx+dz*dz<=threat_radius_sq then threatened=true end
      end
    end
  end
  if champion_threat~=threatened then
    champion_threat=threatened
    update_defense()
  end
end

