local function update_combat_damage()
  local player = game.player.get()
  if not player then return end
  local char_idx = player.character_id or 0
  local level, _, paragon = get_char_progression(char_idx)
  local ranks=skill_ranks()
  local bonus=1.0+(level-1)*setting("damage_per_level_tenths_percent",25,0,250)/1000+
    paragon*setting("paragon_damage_per_rank_tenths_percent",15,0,100)/1000
  bonus=bonus+0.04*(ranks["moonmod.ascension:might.keen_edge"] or 0)
  bonus=bonus+mastery_bonus(player.weapon and player.weapon.id)
  local hp_fraction=(player.max_hp or 0)>0 and (player.hp or 0)/player.max_hp or 1
  if hp_fraction<0.25 then bonus=bonus+0.25*(ranks["moonmod.ascension:vitality.last_stand"] or 0) end
  if berserk_active() then bonus=bonus+0.40 end
  checked(game.combat.register_formula({
    id = formula_id,
    operation = "multiply",
    value = bonus,
    priority = 50
  }))
  local deadly_aim = ranks["moonmod.ascension:might.deadly_aim"] or 0
  local ruthless = ranks["moonmod.ascension:might.ruthless"] or 0
  for character_id in pairs(CHARACTERS) do
    checked(game.combat.register_formula({id="ascension-damage-variance-"..character_id,operation="random_multiply",
      value=1.0,
      min_value=1-setting("damage_variance_percent",10,0,50)/100,
      max_value=1+setting("damage_variance_percent",10,0,50)/100,
      priority=46,character_id=character_id}))
    -- Only the active character's equipped weapon can hit right now. Scope its
    -- speed bonus to that native weapon ID so a stale formula cannot affect a
    -- different weapon after a swap; all other party members retain the base
    -- crit chance until they become active and this formula is refreshed.
    local crit_chance = math.min(100, setting("crit_chance_percent",8,0,100) + 3 * deadly_aim)
    local crit_weapon_id = nil
    if player.character_id == character_id and player.weapon then
      local weapon_speed = tonumber(player.weapon.speed) or 0
      crit_chance = math.min(100, crit_chance + weapon_speed * setting("crit_per_speed_hundredths",5,0,100)/100)
      crit_weapon_id = tonumber(player.weapon.item_no)
    end
    checked(game.combat.register_formula({id="ascension-critical-hit-"..character_id,operation="chance_multiply",
      value=setting("crit_damage_multiplier_percent",175,100,1000)/100+0.20*ruthless,
      chance=crit_chance,priority=47,character_id=character_id,
      weapon_id=crit_weapon_id}))
  end
  local executioner = ranks["moonmod.ascension:might.executioner"] or 0
  checked(game.combat.register_formula({id="ascension-executioner",operation="multiply",
    value=executioner>0 and 1.30 or 1.0,priority=55,target_hp_below_percent=30}))
end

