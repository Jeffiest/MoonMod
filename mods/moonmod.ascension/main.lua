moonmod.on("ui.action",function(action)
  if action.id == "party_progress" then
    local party=game.party.list()
    if not party or #party==0 then game.ui.notify({message="Load a game first"}); return end
    party_cursor=(party_cursor+1)%#party
    local i=party[party_cursor+1].character_id
    local level,xp,paragon=get_char_progression(i)
    local char=game.characters.get({id=CHARACTERS[i]})
    game.ui.notify({message=string.format("%s L%d XP%d Paragon%d HP%d/%d; skill points %d",CHARACTERS[i]:upper(),level,xp,paragon,char.hp,char.max_hp,math.max(0,skill_budget(i)))})
  elseif action.id == "mastery_equipped" then
    local player=game.player.get()
    local weapon_id=player and player.weapon and player.weapon.id or nil
    if not weapon_id then game.ui.notify({message="Equip a weapon to inspect its mastery"}); return end
    local kills=mastery_data()[weapon_id] or 0
    game.ui.notify({message=mastery_summary(weapon_id,kills)})
  elseif action.id == "mastery_browse" then
    local records=mastery_data()
    local ids={}
    for id,kills in pairs(records) do if type(id)=="string" and type(kills)=="number" and kills>0 then ids[#ids+1]=id end end
    table.sort(ids)
    if #ids==0 then game.ui.notify({message="No weapon mastery yet. Defeat enemies with a weapon to begin."}); return end
    mastery_cursor=mastery_cursor%#ids+1
    local id=ids[mastery_cursor]
    local kills=records[id]
    game.ui.notify({message=mastery_summary(id,kills)})
  elseif action.id == "ascension_help" then
    game.ui.notify({message="Defeat enemies for XP. Each character earns skill points and keeps a separate tree. Level and Paragon rewards use Ascension Settings. Skills tab trains the active character; Actions casts learned skills using Focus."})
  elseif action.id == "respec" then
    local player=game.player.get()
    if not player or type(player.character_id)~="number" then game.ui.notify({message="Load a game and select a character first"});return end
    local level=get_char_progression(player.character_id)
    local cost=math.max(0,math.floor(moonmod.settings.get("respec_cost_per_level") or 100))*level
    local wallet=game.economy.get()
    if not wallet or type(wallet.amount)~="number" or wallet.amount<cost then
      game.ui.notify({message="Respec costs "..cost.." Gilda"});return
    end
    local remaining=cost
    while remaining>0 do
      local chunk=math.min(32767,remaining)
      local paid,err=game.economy.spend({amount=chunk})
      if not paid then game.ui.notify({message=type(err)=="table" and err.message or "Could not pay the respec cost"});return end
      remaining=remaining-chunk
    end
    local listed=game.skills.list()
    local owned={}
    for _,skill in ipairs((listed and listed.skills) or {}) do
      if type(skill.id)=="string" and skill.id:sub(1,18)=="moonmod.ascension:" then owned[#owned+1]=skill.id end
    end
    for _,id in ipairs(owned) do checked(game.skills.set_rank({id=id,rank=0})) end
    -- Persist the reset into this character's profile immediately; otherwise
    -- switching characters would restore the pre-respec ranks from storage.
    save_slot_skills(active_native_slot_key, player.character_id)
    focus=math.min(focus,focus_max())
    update_defense()
    update_combat_damage()
    game.ui.notify({message=CHARACTERS[player.character_id]:upper().."'s skills reset for "..cost.." Gilda. Available points: "..math.max(0,skill_budget(player.character_id))})
  end
end)
