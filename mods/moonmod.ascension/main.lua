    if event.entity and event.element~=1 and math.random()<0.05 then
      pcall(game.combat.status_add,{entity=event.entity,status="stop",duration_frames=180})
    end
  elseif item==EXPANDED_WEAPONS.cactus and character then
    pcall(game.player.thirst_set,{restore=event.damage/10,character=character})
